use crate::config::{grpc_path_pattern, validate_domain, validate_target, Config};
use crate::credentials::{self, Accounts};
use anyhow::{ensure, Context, Result};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::Path;

const OUTPOST_PATH: &str = "/outpost.goauthentik.io";
const AUTHENTIK_HEADERS: &[&str] = &[
    "X-Authentik-Username",
    "X-Authentik-Groups",
    "X-Authentik-Entitlements",
    "X-Authentik-Email",
    "X-Authentik-Name",
    "X-Authentik-Uid",
    "X-Authentik-Jwt",
    "X-Authentik-Meta-Jwks",
    "X-Authentik-Meta-Outpost",
    "X-Authentik-Meta-Provider",
    "X-Authentik-Meta-App",
    "X-Authentik-Meta-Version",
];

fn render_forward_auth(output: &mut String, outpost: &str) {
    write!(
        output,
        "\t\t@outpost path {OUTPOST_PATH} {OUTPOST_PATH}/*\n\
         \t\trequest_header -X-Authentik-*\n\
         \t\trequest_header -X-Authentik_*\n\
         \t\trequest_header -X_Authentik-*\n\
         \t\trequest_header -X_Authentik_*\n\
         \t\treverse_proxy @outpost {outpost} {{\n\
         \t\t\theader_up Host {{http.request.host}}\n\
         \t\t\theader_up X-Original-URL {{scheme}}://{{http.request.hostport}}{{uri}}\n\
         \t\t}}\n\
         \t\treverse_proxy {outpost} {{\n\
         \t\t\tmethod GET\n\
         \t\t\trewrite {OUTPOST_PATH}/auth/caddy\n\
         \t\t\theader_up X-Forwarded-Method {{http.request.method}}\n\
         \t\t\theader_up X-Forwarded-Uri {{http.request.uri}}\n\
         \t\t\t@authorized status 2xx\n\
         \t\t\thandle_response @authorized {{\n\
         \t\t\t\tcopy_response_headers {{\n\
         \t\t\t\t\tinclude Set-Cookie\n\
         \t\t\t\t}}\n"
    )
    .unwrap();
    for (index, name) in AUTHENTIK_HEADERS.iter().enumerate() {
        let value = format!("{{rp.header.{name}}}");
        writeln!(
            output,
            "\t\t\t\t@claim_{index} not vars {value} \"\"\n\
             \t\t\t\trequest_header @claim_{index} {name} {value}"
        )
        .unwrap();
    }
    output.push_str("\t\t\t}\n\t\t}\n");
}

pub fn render(
    config: &Config,
    login_dir: &Path,
    updated_group: Option<(&str, &Accounts)>,
) -> Result<String> {
    let mut output =
        String::from("# Generated by web-distributor. Edit the TOML configuration instead.\n");
    let mut hosts = BTreeSet::new();
    let mut login_cache = BTreeMap::new();

    for (domain, target) in &config.routes {
        validate_domain(domain)?;
        ensure!(
            hosts.insert(domain.to_ascii_lowercase()),
            "duplicate site hostname {domain:?}"
        );
        validate_target(target).with_context(|| format!("route for {domain}"))?;
        writeln!(output, "\n{domain} {{").unwrap();
        output.push_str("\troute {\n\t\theader Strict-Transport-Security max-age=63072000\n");

        if let Some(group) = config.login_groups.get(domain) {
            let accounts = match updated_group {
                Some((name, accounts)) if name == group => accounts,
                _ => {
                    if !login_cache.contains_key(group) {
                        let path = credentials::group_path(login_dir, group)?;
                        let accounts = credentials::read(&path)
                            .with_context(|| format!("login group for {domain}"))?;
                        login_cache.insert(group, accounts);
                    }
                    &login_cache[group]
                }
            };
            output.push_str("\t\tbasic_auth bcrypt login {\n");
            for (name, hash) in accounts {
                writeln!(output, "\t\t\t\"{name}\" {hash}").unwrap();
            }
            output.push_str("\t\t}\n");
        }

        if let Some(prefix) = config.grpc_prefix.get(domain) {
            let pattern =
                grpc_path_pattern(prefix).with_context(|| format!("gRPC route for {domain}"))?;
            write!(
                output,
                "\t\t@grpc path_regexp {pattern}\n\
                 \t\treverse_proxy @grpc h2c://{target} {{\n\
                 \t\t\theader_up Host {target}\n\
                 \t\t}}\n"
            )
            .unwrap();
        }

        if let Some(outpost) = config.forward_auth.get(domain) {
            validate_target(outpost).with_context(|| format!("forward auth for {domain}"))?;
            render_forward_auth(&mut output, outpost);
        }

        write!(
            output,
            "\t\treverse_proxy {target} {{\n\
             \t\t\theader_up Host {{http.request.hostport}}\n\
             \t\t\theader_up X-Real-IP {{http.request.remote.host}}\n\
             \t\t\theader_up X-Scheme {{scheme}}\n\
             \t\t}}\n\t}}\n}}\n"
        )
        .unwrap();
    }

    for domain in &config.certificate_only {
        validate_domain(domain)?;
        ensure!(
            hosts.insert(domain.to_ascii_lowercase()),
            "duplicate site hostname {domain:?}"
        );
        writeln!(
            output,
            "\n{domain} {{\n\theader Strict-Transport-Security max-age=63072000\n\trespond 404\n}}"
        )
        .unwrap();
    }

    Ok(output)
}
